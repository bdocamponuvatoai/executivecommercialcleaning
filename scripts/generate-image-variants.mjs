// Writes the responsive sizes of every image in src/assets/images to
// public/image-variants, plus the lookup module the next/image loader reads
// (src/lib/image-variants.ts).
//
//   npm run images          regenerate after adding or changing an image
//   npm run images:check    fail if the committed files are out of date (CI)
//
// public/ is copied by `next build` itself, so every host deploys these files.
// Each name carries a hash of its source and settings, so they can be cached
// forever (see vercel.json). This folder is owned by this script: it is
// emptied and rewritten on every run.
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IMAGES_DIR = path.join(ROOT, "src/assets/images");
const PUBLIC_PATH = "/image-variants";
const VARIANTS_DIR = path.join(ROOT, "public", PUBLIC_PATH);
const MODULE_FILE = path.join(ROOT, "src/lib/image-variants.ts");
const SIZES_FILE = path.join(ROOT, "src/config/image-sizes.json");
const QUALITY = { webp: 74, png: 90, jpg: 80, jpeg: 80 };
const CHECK = process.argv.includes("--check");

const { deviceSizes, imageSizes } = JSON.parse(
  await readFile(SIZES_FILE, "utf8"),
);
const widths = [...new Set([...imageSizes, ...deviceSizes])].sort(
  (a, b) => a - b,
);

const identifier = (name) =>
  name.replace(/[^a-z0-9]+([a-z0-9])/gi, (_, c) => c.toUpperCase());
const sha256 = (...parts) => {
  const hash = createHash("sha256");
  for (const part of parts) hash.update(part);
  return hash.digest("hex");
};

const sources = [];
for (const entry of await readdir(IMAGES_DIR, { withFileTypes: true })) {
  const match = entry.isFile() && /^(.+)\.(webp|png|jpe?g)$/i.exec(entry.name);
  if (!match) continue;
  const [file, name, rawExt] = match;
  const ext = rawExt.toLowerCase();
  const buffer = await readFile(path.join(IMAGES_DIR, file));
  const { width } = await sharp(buffer).metadata();
  const variants = widths
    .filter((w) => w < width)
    .map((w) => {
      const hash = sha256(buffer, `|w${w}|q${QUALITY[ext]}`).slice(0, 10);
      return { width: w, file: `${name}.w${w}.${hash}.${ext}` };
    });
  sources.push({
    file,
    ext,
    buffer,
    width,
    hash: sha256(buffer).slice(0, 16),
    id: identifier(name),
    variants,
  });
}
sources.sort((a, b) => a.file.localeCompare(b.file));

const imports = sources.map(
  (s) => `import ${s.id} from "@/assets/images/${s.file}";`,
);
const entries = sources.map((s) => {
  const pairs = s.variants.map(
    (v) => `[${v.width}, "${PUBLIC_PATH}/${v.file}"]`,
  );
  return (
    `  // ${s.file}: ${s.width}px, sha256 ${s.hash}\n` +
    `  { original: ${s.id}, variants: [${pairs.join(", ")}] },`
  );
});

const source = `// Generated by scripts/generate-image-variants.mjs. Do not edit by hand.
// Run \`npm run images\` after adding or changing a file in src/assets/images.
// Widths come from src/config/image-sizes.json.
import type { StaticImageData } from "next/image";
${imports.join("\n")}

type ImageVariants = {
  original: StaticImageData;
  /** Narrower copies in public${PUBLIC_PATH}, smallest first. */
  variants: [width: number, url: string][];
};

const entries: ImageVariants[] = [
${entries.join("\n")}
];

/** Keyed by the original's URL, which is the \`src\` the loader receives. */
export const imageVariants = new Map(
  entries.map((entry) => [entry.original.src, entry]),
);
`;
const expected = await prettier.format(source, {
  ...(await prettier.resolveConfig(MODULE_FILE)),
  filepath: MODULE_FILE,
});
const wanted = new Set(sources.flatMap((s) => s.variants.map((v) => v.file)));

if (CHECK) {
  const problems = [];
  const current = await readFile(MODULE_FILE, "utf8").catch(() => "");
  if (current !== expected)
    problems.push(`${path.relative(ROOT, MODULE_FILE)} is out of date`);
  const present = new Set(await readdir(VARIANTS_DIR).catch(() => []));
  for (const file of wanted)
    if (!present.has(file)) problems.push(`missing ${file}`);
  for (const file of present)
    if (!wanted.has(file)) problems.push(`unexpected ${file}`);
  if (problems.length) {
    console.error(
      `Image variants are out of date. Run \`npm run images\`.\n- ${problems.join("\n- ")}`,
    );
    process.exit(1);
  }
  console.log(`Image variants up to date (${wanted.size} files).`);
} else {
  await rm(VARIANTS_DIR, { recursive: true, force: true });
  await mkdir(VARIANTS_DIR, { recursive: true });
  for (const s of sources) {
    const format = s.ext === "jpg" ? "jpeg" : s.ext;
    for (const v of s.variants) {
      await sharp(s.buffer)
        .resize({ width: v.width })
        [format]({ quality: QUALITY[s.ext] })
        .toFile(path.join(VARIANTS_DIR, v.file));
    }
  }
  await writeFile(MODULE_FILE, expected);
  console.log(
    `Wrote ${wanted.size} image variants for ${sources.length} images and ${path.relative(ROOT, MODULE_FILE)}.`,
  );
}
